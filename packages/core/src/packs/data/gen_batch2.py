import subprocess
import codecs

# We will generate a powershell script that writes these files using Set-Content
ps_script_path = os.path.join(base_dir, 'run_set_content.ps1')

with codecs.open(ps_script_path, 'w', encoding='utf-8') as f:
    f.write("$ErrorActionPreference = 'Stop'\n")
    for pack in packs:
        # TS content
        ts_lines = [
            "import type { WordEntry } from '../../../types/packs'",
            "",
            f"export const {pack['var_name']}: WordEntry[] = ["
        ]
        json_words = []
        for i, (word, hints) in enumerate(pack['words']):
            entry_id = f"{pack['id']}_{i+1}"
            ts_lines.append(f'  {{ "id": "{entry_id}", "word": "{word}", "category": "{pack["category"]}", "hints": {json.dumps(hints)} }},')
            json_words.append({ "word": word, "hints": hints })
            
        ts_lines[-1] = ts_lines[-1].rstrip(',')
        ts_lines.append("] as const")
        
        json_obj = {
            "id": pack['id'],
            "name": pack['name'],
            "emoji": pack['emoji'],
            "description": pack['description'],
            "words": json_words
        }
        
        ts_path = os.path.join(ts_dir, pack['ts_file']).replace('\\', '/')
        json_path = os.path.join(base_dir, pack['json_file']).replace('\\', '/')
        
        ts_content = "\n".join(ts_lines)
        json_content = json.dumps(json_obj, indent=2)
        
        f.write(f"\n$tsContent = @'\n{ts_content}\n'@\n")
        f.write(f"Set-Content -Path '{ts_path}' -Value $tsContent -Encoding UTF8\n")
        
        f.write(f"\n$jsonContent = @'\n{json_content}\n'@\n")
        f.write(f"Set-Content -Path '{json_path}' -Value $jsonContent -Encoding UTF8\n")
        
print("Python script ready.")
